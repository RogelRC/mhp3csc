// Generates src/lib/mh3/charmTableMembers.ts from mhp3db's full charm dump.
//
// Source: https://raw.githubusercontent.com/mhp3db/mhp3db.github.io/main/scripts/charm-search/charms.js
// It lists every real MHP3rd talisman occurrence (129600 rows = 5400 x 12 tables)
// with its skills, slots and the charm table it belongs to.
//
// Usage: node scripts/generate-charm-table-members.mjs [path/to/charms.js]
// The output maps CHARM_TABLE-style tuples to a bitmask of tables (bit i => table i+1).

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'src/lib/mh3/charmTableMembers.ts');
const SOURCE_URL =
	'https://raw.githubusercontent.com/mhp3db/mhp3db.github.io/main/scripts/charm-search/charms.js';

const inputPath = process.argv[2];
if (!inputPath) {
	console.error(
		`Usage: node scripts/generate-charm-table-members.mjs <path-to-charms.js>\nDownload it first:\n  curl -o charms.js ${SOURCE_URL}`
	);
	process.exit(1);
}

// mhp3db spells this tree without the space used by CHARM_TREE_NAMES.
const TREE_ALIASES = new Map([['ThundrAtk', 'Thundr Atk']]);

function loadTreeNames() {
	const src = readFileSync(path.join(root, 'src/lib/mh3/charmTable.ts'), 'utf8');
	const match = src.match(/export const CHARM_TREE_NAMES = \[([\s\S]*?)\];/);
	if (!match) throw new Error('CHARM_TREE_NAMES not found in charmTable.ts');
	return eval(`[${match[1]}]`);
}

function parseSkill(text, treeIndex) {
	const match = text.match(/^(.*) (-?\d+)$/);
	if (!match) throw new Error(`Unparseable skill string: "${text}"`);
	const tree = TREE_ALIASES.get(match[1]) ?? match[1];
	const idx = treeIndex.indexOf(tree);
	if (idx < 0) throw new Error(`Unknown skill tree: "${match[1]}"`);
	return { idx, points: Number(match[2]) };
}

const treeNames = loadTreeNames();

const raw = readFileSync(inputPath, 'utf8');
const entries = JSON.parse(raw.slice(raw.indexOf('['), raw.lastIndexOf(']') + 1));

/** @type {Map<string, number>} profile key -> bitmask of tables */
const profiles = new Map();
for (const e of entries) {
	const s1 = parseSkill(e['Skill 1'], treeNames);
	const s2 = e['Skill 2'] ? parseSkill(e['Skill 2'], treeNames) : null;
	const slots = Number(e['Charm Slot']);
	const table = Number(e['Table No.']);
	if (!(table >= 1 && table <= 12)) throw new Error(`Bad table number: ${table}`);
	// The same skills+slots tuple can surface under several talisman names
	// (Common/Queen/King/Dragon) depending on the source item, so the profile
	// key intentionally ignores the name.
	const key = `${s1.idx}|${s1.points}|${s2 ? s2.idx : -1}|${s2 ? s2.points : 0}|${slots}`;
	profiles.set(key, (profiles.get(key) ?? 0) | (1 << (table - 1)));
}

console.log(`source entries: ${entries.length}`);
console.log(`unique profiles: ${profiles.size}`);

// Validate against the searchable CHARM_TABLE: every row must resolve to a profile.
const charmTableSrc = readFileSync(path.join(root, 'src/lib/mh3/charmTable.ts'), 'utf8');
const rowsMatch = charmTableSrc.match(/export const CHARM_TABLE = \[([\s\S]*)\];/);
const charmRows = eval(`[${rowsMatch[1]}]`);
let matched = 0;
for (const [t1, p1, t2, p2, slots] of charmRows) {
	const key = `${t1}|${p1}|${t2}|${p2}|${slots}`;
	if (!profiles.has(key)) {
		throw new Error(
			`CHARM_TABLE row not found in source data: ${key} (${[t1, p1, t2, p2, slots]})`
		);
	}
	matched++;
}
console.log(`CHARM_TABLE rows matched: ${matched}/${charmRows.length}`);

// Emit only the profiles the search engine can produce, keyed as above.
const outputEntries = [];
for (const [t1, p1, t2, p2, slots] of charmRows) {
	const key = `${t1}|${p1}|${t2}|${p2}|${slots}`;
	outputEntries.push([key, profiles.get(key)]);
}
outputEntries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));

const body = outputEntries.map(([key, mask]) => `\t'${key}': ${mask}`).join(',\n');
const banner = [
	'// Auto-generated by scripts/generate-charm-table-members.mjs — do not edit.',
	'// Source: mhp3db.github.io charm dump (all 12 official MHP3rd charm tables).',
	'// Each entry covers one CHARM_TABLE row; the value is a bitmask where bit i',
	'// set means the talisman appears in charm table i+1.',
	''
].join('\n');

writeFileSync(
	outputPath,
	`${banner}export const CHARM_PROFILE_TABLES: Readonly<Record<string, number>> = {\n${body}\n};\n`
);
console.log(`wrote ${outputPath} (${outputEntries.length} entries)`);
